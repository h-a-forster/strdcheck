"""The StRD dataset manifest: names, suites, source URLs and SHA-256 checksums.

The manifest (``strdcheck/data/manifest.json``) is generated by
``scripts/build_manifest.py``. The data files themselves are not distributed with
strdcheck; :mod:`strdcheck.fetch` downloads them from NIST and verifies them against the
checksums recorded here.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from importlib import resources
from typing import Literal

Suite = Literal["univariate", "anova", "linear", "nonlinear"]
SUITES: tuple[Suite, ...] = ("univariate", "anova", "linear", "nonlinear")
DIFFICULTIES = ("lower", "average", "higher")


@dataclass(frozen=True, slots=True)
class DatasetInfo:
    """Manifest entry for one StRD file."""

    name: str
    suite: Suite
    url: str
    sha256: str
    bytes: int
    difficulty: str
    n_obs: int

    @property
    def filename(self) -> str:
        return f"{self.name}.dat"


@cache
def _load() -> dict[str, object]:
    text = resources.files("strdcheck").joinpath("data/manifest.json").read_text("utf-8")
    return json.loads(text)


def manifest_meta() -> dict[str, str]:
    """Source, DOI, base URL and retrieval date of the manifest."""
    raw = _load()
    return {k: str(v) for k, v in raw.items() if k != "datasets"}


@cache
def all_datasets() -> tuple[DatasetInfo, ...]:
    """Every manifest entry, in NIST's order within each suite."""
    entries = _load()["datasets"]
    assert isinstance(entries, list)
    return tuple(DatasetInfo(**e) for e in entries)


def list_datasets(
    suite: Suite | None = None, difficulty: str | None = None
) -> tuple[DatasetInfo, ...]:
    """Manifest entries filtered by suite and/or difficulty."""
    if suite is not None and suite not in SUITES:
        raise ValueError(f"unknown suite {suite!r}; expected one of {SUITES}")
    if difficulty is not None and difficulty not in DIFFICULTIES:
        raise ValueError(f"unknown difficulty {difficulty!r}; expected one of {DIFFICULTIES}")
    return tuple(
        d
        for d in all_datasets()
        if (suite is None or d.suite == suite)
        and (difficulty is None or d.difficulty == difficulty)
    )


def get_dataset_info(name: str) -> DatasetInfo:
    """Manifest entry by dataset name (case-insensitive)."""
    for d in all_datasets():
        if d.name.lower() == name.lower():
            return d
    raise KeyError(f"unknown StRD dataset {name!r}")
